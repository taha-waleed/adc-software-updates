#!/usr/bin/env python3
"""MediLab X 10.0.7: add Fish Tank without replacing any existing feature code."""
from pathlib import Path
import base64, hashlib, json, re, subprocess, tempfile, zlib

ROOT=Path(__file__).resolve().parents[1]
MANIFEST=ROOT/'m/update.json'
SOURCE=ROOT/'medilabx-ui-10.0.6/MediLabX.html'
DEST=ROOT/'medilabx-ui-10.0.7/MediLabX.html'
PATCH=ROOT/'m/ux-10.0.7.patch.b64'
EXPECTED_BASE='0c5058903733d84cf09f06035b9f8d56f8323bf93842e0492f5262173a993fca'
EXPECTED_PATCH='a4557cc12779cd93dc3aa52411b5bb7366ee2a223e123bb53bafd14f19f7f4ae'
OLD_URL='https://raw.githubusercontent.com/taha-waleed/adc-software-updates/main/medilabx-ui-10.0.6/MediLabX.html'
NEW_URL='https://raw.githubusercontent.com/taha-waleed/adc-software-updates/main/medilabx-ui-10.0.7/MediLabX.html'
MARK='mlx107-fishtank-settings-and-animation'
REQUIRED=['id="settings"','data-setting-view="appearance"','id="adc85Titlebar"','id="adcSettingsList"','id="adc85UpdateCentre"','mlx106-clinical-validation-and-dialogs']

def sha(data):return hashlib.sha256(data).hexdigest()
def publish():
    manifest=json.loads(MANIFEST.read_text('utf-8'))
    if manifest.get('version')=='10.0.7':
        if manifest.get('htmlUrl')==NEW_URL and DEST.is_file() and sha(DEST.read_bytes())==manifest.get('sha256'):
            print('PASS: already-published 10.0.7 verified');return
        raise RuntimeError('10.0.7 manifest mismatched; refusing to replace the existing release')
    if (manifest.get('version'),manifest.get('htmlUrl'),manifest.get('sha256'))!=('10.0.6',OLD_URL,EXPECTED_BASE):
        raise RuntimeError('Expected installed update channel 10.0.6 was changed. Publish aborted.')
    source=SOURCE.read_bytes()
    if sha(source)!=EXPECTED_BASE:raise RuntimeError('Source 10.0.6 checksum mismatch. Aborted.')
    html=source.decode('utf-8')
    missing=[x for x in REQUIRED if x not in html]
    if missing:raise RuntimeError('Missing source controls: '+', '.join(missing))
    patch=zlib.decompress(base64.b64decode(''.join(PATCH.read_text('ascii').split())))
    if sha(patch)!=EXPECTED_PATCH:raise RuntimeError('Fish Tank patch failed SHA-256 verification')
    frag=patch.decode('utf-8')
    if frag.count(MARK)!=1 or html.count(MARK)!=0:raise RuntimeError('Patch marker duplicated or missing')
    match=re.search(r'<script id="mlx107-fishtank-settings-and-animation">(.*?)</script>',frag,re.S)
    if not match:raise RuntimeError('Fish Tank script not found')
    sprite=re.search(r"const SPRITE='data:image/webp;base64,([^']+)'",match.group(1))
    if not sprite:raise RuntimeError('Embedded fish art missing')
    image=base64.b64decode(sprite.group(1))
    if image[:4]!=b'RIFF' or image[8:12]!=b'WEBP':raise RuntimeError('Fish image is not a valid WebP file')
    with tempfile.TemporaryDirectory() as folder:
        js=Path(folder)/'fish_107.js';js.write_text(match.group(1),'utf-8')
        subprocess.run(['node','--check',str(js)],check=True)
    pivot=html.rfind('</body>')
    if pivot<0 or html.rfind('</html>')<0:raise RuntimeError('HTML closing tags missing')
    output=(html[:pivot]+frag+'\n'+html[pivot:]).encode('utf-8')
    if output.replace(patch+b'\n',b'',1)!=source:raise RuntimeError('Original HTML changed outside the additive patch')
    DEST.parent.mkdir(parents=True,exist_ok=True)
    if DEST.exists() and DEST.read_bytes()!=output:raise RuntimeError('Existing version file differs; do not overwrite')
    if not DEST.exists():DEST.write_bytes(output)
    manifest.update(version='10.0.7',htmlUrl=NEW_URL,sha256=sha(output))
    manifest['notes']=[
      'Miniature Midnight Fish Tank in the existing taskbar; taskbar height is not increased.',
      '10 photorealistic AI-drawn tropical fish, with swim speed 84 and ambient water bubbles enabled by default.',
      'Settings > Appearance now contains Fish Tank controls: theme, species, fish count, speed, bubbles, visibility, pause, feeding, and reset.',
      'All fish artwork is embedded for offline use; animation pauses when hidden and respects reduced-motion preferences.',
      'No clinical data, receipts, doctor directory, login, Developer Corner, or Electron updater transport modified.'
    ]
    MANIFEST.write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n','utf-8')
    print('PASS: 10.0.6 source bytes retained:',len(source))
    print('PASS: embedded sprite bytes:',len(image))
    print('PASS: 10.0.7 generated bytes:',len(output),'SHA256:',sha(output))
    print('PASS: correct MediLab X update channel manifest generated')
if __name__=='__main__':publish()
