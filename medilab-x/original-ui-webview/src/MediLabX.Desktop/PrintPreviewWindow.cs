using Microsoft.Web.WebView2.Core;
using Microsoft.Web.WebView2.Wpf;
using System;
using System.Threading.Tasks;
using System.Windows;
using System.Windows.Controls;
using System.Windows.Media;
namespace MediLabX.Desktop;
internal static class PrintPreviewWindow
{
 public static async Task<object> ShowAsync(Window owner,string html,string profile)
 {
  try
  {
   // Content is never written as plaintext to a temp file.
   var viewer=new WebView2();
   var w=new Window{Title="MediLab X — Print Preview",Owner=owner,Width=935,Height=790,MinWidth=620,MinHeight=500,
     WindowStartupLocation=WindowStartupLocation.CenterOwner,Background=Brushes.White};
   var root=new DockPanel();
   var toolbar=new StackPanel{Orientation=Orientation.Horizontal,Background=new SolidColorBrush(Color.FromRgb(234,241,252)),Height=52};
   var print=new Button{Content="Print receipt / report",Margin=new Thickness(14,9,8,9),Padding=new Thickness(15,2,15,2),MinWidth=175};
   var close=new Button{Content="Close",Margin=new Thickness(0,9,0,9),Padding=new Thickness(12,2,12,2)};
   toolbar.Children.Add(print);toolbar.Children.Add(close);
   DockPanel.SetDock(toolbar,Dock.Top);root.Children.Add(toolbar);root.Children.Add(viewer);w.Content=root;
   close.Click+=(_,_)=>w.Close();
   print.Click+=(_,_)=>
   {
    try{viewer.CoreWebView2?.ShowPrintUI(CoreWebView2PrintDialogKind.Browser);}
    catch(Exception ex){MessageBox.Show(w,ex.Message,"Print error",MessageBoxButton.OK,MessageBoxImage.Error);}
   };
   w.Closed+=(_,_)=>viewer.Dispose();
   w.Show();
   await viewer.EnsureCoreWebView2Async();
   var printable="<!doctype html><html><head><meta charset=\"utf-8\"><style>@page{size:A4;margin:0}body{background:#fff;color:#111}</style></head><body>";
   // HTML is generated by the app's existing approved receipt/report templates.
   // Do not silently alter their letterhead sizes or patient details.
   viewer.NavigateToString(html.StartsWith("<!doctype",StringComparison.OrdinalIgnoreCase)||html.Contains("<html",StringComparison.OrdinalIgnoreCase)?html:printable+html+"</body></html>");
   return new{ok=true};
  }
  catch(Exception ex){Diagnostics.Write("Print preview error: "+ex.GetType().Name);return new{ok=false,error=ex.Message};}
 }
}